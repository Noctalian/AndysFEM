pub const FENICSX_PY: &str = r#"# Generated by fem-client: FEniCSx (DOLFINx 0.11 + dolfinx_mpc) periodic homogenisation.
# The physics is a weak form: find the periodic fluctuation v with u = E.x + v.
# Periodic pairing: dolfinx_mpc slave elimination; stress: assembled volume average.
import json
import numpy as np
import ufl
from mpi4py import MPI
import dolfinx
from dolfinx import fem
import dolfinx_mpc

P = json.load(open("params.json"))
L, E, nu = P["L"], P["E"], P["nu"]
try:
    from dolfinx.io import gmsh as gmshio  # 0.10+
except ImportError:
    from dolfinx.io import gmshio
res = gmshio.read_from_msh("cell.msh", MPI.COMM_WORLD, 0, gdim=2)
mesh = res.mesh if hasattr(res, "mesh") else res[0]
V = fem.functionspace(mesh, ("Lagrange", P["order"], (2,)))
mu = E / (2 * (1 + nu))
lmbda = E * nu / (1 - nu ** 2)  # plane stress
def eps(w):
    return ufl.sym(ufl.grad(w))
def sigma(e):
    return lmbda * ufl.tr(e) * ufl.Identity(2) + 2 * mu * e
tol = 1e-8 * L
ax, ay = json.load(open("geometry.json"))["anchor"]
pin = fem.locate_dofs_geometrical(V, lambda x: np.isclose(x[0], ax, atol=tol) & np.isclose(x[1], ay, atol=tol))
bc = fem.dirichletbc(np.zeros(2, dtype=dolfinx.default_scalar_type), pin, V)
mpc = dolfinx_mpc.MultiPointConstraint(V)
def on_right(x):
    return np.isclose(x[0], L / 2, atol=tol) & ~np.isclose(x[1], L / 2, atol=tol)
def to_left(x):
    y = x.copy(); y[0] = x[0] - L; return y
def on_top(x):
    return np.isclose(x[1], L / 2, atol=tol)
def to_bottom(x):
    y = x.copy(); y[1] = x[1] - L
    y[0] = np.where(np.isclose(x[0], L / 2, atol=tol), x[0] - L, x[0])  # top-right corner -> bottom-left
    return y
mpc.create_periodic_constraint_geometrical(V, on_right, to_left, [bc])
mpc.create_periodic_constraint_geometrical(V, on_top, to_bottom, [bc])
mpc.finalize()
v, w = ufl.TrialFunction(V), ufl.TestFunction(V)
Ebar = fem.Constant(mesh, np.zeros((2, 2)))
a_form = ufl.inner(sigma(eps(v)), eps(w)) * ufl.dx
l_form = -ufl.inner(sigma(Ebar), eps(w)) * ufl.dx
problem = dolfinx_mpc.LinearProblem(a_form, l_form, mpc, bcs=[bc],
                                    petsc_options={"ksp_type": "preonly", "pc_type": "lu"})
averages = []
for k, (exx, eyy, gxy) in enumerate(P["strain_cases"]):
    Ebar.value = np.array([[exx, gxy / 2], [gxy / 2, eyy]])
    vh = problem.solve()
    S = sigma(Ebar + eps(vh))
    avg = [mesh.comm.allreduce(fem.assemble_scalar(fem.form(S[i, j] * ufl.dx)), op=MPI.SUM) / L ** 2
           for i, j in ((0, 0), (1, 1), (0, 1))]
    averages.append(avg)
    if k == 0 and P["order"] == 1:
        with dolfinx.io.XDMFFile(mesh.comm, "fields_fenicsx.xdmf", "w") as f:
            f.write_mesh(mesh)
            f.write_function(vh)
if mesh.comm.rank == 0:
    json.dump({"schema": "fem-client/raw@1", "engine": "fenicsx",
               "engine_version": "dolfinx %s, dolfinx_mpc %s" % (dolfinx.__version__, getattr(dolfinx_mpc, "__version__", "?")),
               "strain_cases": P["strain_cases"], "stress_averages": averages,
               "pairing": "dolfinx_mpc slave elimination", "stress_route": "assembled volume average",
               "fields": "fields_fenicsx.xdmf"}, open("results.json", "w"), indent=1)
"#;

