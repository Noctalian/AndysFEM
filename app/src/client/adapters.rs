/// the shared geometry script (Gmsh Python API) — run once per case, identical for every engine
pub const GEOMETRY_PY: &str = r#"# Generated by fem-client: geometry + mesh of the periodic unit cell (Gmsh Python API).
import json, math
import gmsh

P = json.load(open("params.json"))
G = P["groups"]
L, a, t = P["L"], P["a"], P["t"]
th = math.radians(P["theta_deg"])
gmsh.initialize()
gmsh.option.setNumber("General.Terminal", 1)
gmsh.option.setNumber("Mesh.RandomSeed", P["seed"])
gmsh.model.add("cell")
occ = gmsh.model.occ
box = occ.addRectangle(-L / 2, -L / 2, 0, L, L)
if P["kind"] == "homogeneous":
    cell = [(2, box)]
else:
    s = L / 2
    parts, hinges = [], []
    for cx, cy, sg in [(-s / 2, -s / 2, 1), (s / 2, s / 2, 1), (-s / 2, s / 2, -1), (s / 2, -s / 2, -1)]:
        r = occ.addRectangle(cx - a / 2, cy - a / 2, 0, a, a)
        occ.rotate([(2, r)], cx, cy, 0, 0, 0, 1, sg * th)
        parts.append((2, r))
        for dx, dy in [(a / 2, a / 2), (-a / 2, a / 2), (-a / 2, -a / 2), (a / 2, -a / 2)]:
            x = cx + dx * math.cos(sg * th) - dy * math.sin(sg * th)
            y = cy + dx * math.sin(sg * th) + dy * math.cos(sg * th)
            if not any(abs(x - p[0]) < 1e-9 * L and abs(y - p[1]) < 1e-9 * L for p in hinges):
                hinges.append((x, y))
    disks = [(2, occ.addDisk(x, y, 0, t / 2, t / 2)) for x, y in hinges]
    fused, _ = occ.fuse(parts[:1], parts[1:] + disks)
    cell, _ = occ.intersect(fused, [(2, box)])
occ.synchronize()

eps = 1e-6 * L
def inbox(dim, x0, y0, x1, y1):
    return [tag for d, tag in gmsh.model.getEntitiesInBoundingBox(x0 - eps, y0 - eps, -eps, x1 + eps, y1 + eps, eps, dim)]
left = inbox(1, -L / 2, -L / 2, -L / 2, L / 2)
right = inbox(1, L / 2, -L / 2, L / 2, L / 2)
bottom = inbox(1, -L / 2, -L / 2, L / 2, -L / 2)
top = inbox(1, -L / 2, L / 2, L / 2, L / 2)
surfs = [tag for d, tag in cell]
gmsh.model.addPhysicalGroup(1, left, G["left"], "left")
gmsh.model.addPhysicalGroup(1, right, G["right"], "right")
gmsh.model.addPhysicalGroup(1, bottom, G["bottom"], "bottom")
gmsh.model.addPhysicalGroup(1, top, G["top"], "top")
gmsh.model.addPhysicalGroup(2, surfs, G["solid"], "solid")
pts = inbox(0, -L / 2, -L / 2, -L / 2, L / 2)
anchor = sorted(pts, key=lambda p: gmsh.model.getValue(0, p, [])[1])[0]
gmsh.model.addPhysicalGroup(0, [anchor], G["anchor"], "anchor")
ax, ay, _ = gmsh.model.getValue(0, anchor, [])
corner = inbox(0, L / 2, L / 2, L / 2, L / 2)
if corner:
    gmsh.model.addPhysicalGroup(0, corner[:1], G["corner_tr"], "corner_tr")
# identical meshes on opposite faces (each engine still pairs the nodes itself)
T = lambda dx, dy: [1, 0, 0, dx, 0, 1, 0, dy, 0, 0, 1, 0, 0, 0, 0, 1]
if right and left:
    gmsh.model.mesh.setPeriodic(1, right, left, T(L, 0))
if top and bottom:
    gmsh.model.mesh.setPeriodic(1, top, bottom, T(0, L))
gmsh.option.setNumber("Mesh.MeshSizeMax", P["mesh_size"])
gmsh.option.setNumber("Mesh.MshFileVersion", 4.1)
gmsh.model.mesh.generate(2)
gmsh.model.mesh.setOrder(P["order"])
gmsh.write("cell.msh")
area = sum(occ.getMass(2, s) for s in surfs)
ntags, _, _ = gmsh.model.mesh.getNodes()
json.dump({"cell_area": L * L, "solid_area": area, "porosity": 1 - area / (L * L),
           "anchor": [ax, ay], "n_nodes": len(ntags), "gmsh": gmsh.__version__,
           "n_left": len(left), "n_right": len(right), "n_bottom": len(bottom), "n_top": len(top)},
          open("geometry.json", "w"), indent=1)
gmsh.finalize()
"#;

/// mesh conversion with meshlane + round-trip checks (node count, area, group names)
pub const CONVERT_PY: &str = r#"# Generated by fem-client: convert cell.msh to the engine format with meshlane and check it.
import json, sys
from importlib.metadata import version
import numpy as np
import meshlane

fmt = sys.argv[1]
src = meshlane.read("cell.msh")
out = "cell." + fmt
if fmt != "msh":
    meshlane.write(out, src)
dst = meshlane.read(out)

def area(m):
    tot = 0.0
    for block in m.cells:
        if block.type.startswith("triangle") or block.type.startswith("quad"):
            p = m.points[block.data[:, :3 if block.type.startswith("triangle") else 4]][:, :, :2]
            x, y = p[:, :, 0], p[:, :, 1]
            tot += float(np.abs(0.5 * np.sum(x * np.roll(y, -1, axis=1) - np.roll(x, -1, axis=1) * y, axis=1)).sum())
    return tot

def groups(m):
    names = set(getattr(m, "field_data", {}).keys())
    names |= set(getattr(m, "cell_sets", {}).keys()) | set(getattr(m, "point_sets", {}).keys())
    return sorted(str(n).lower() for n in names)

need = ["left", "right", "bottom", "top", "solid", "anchor"]
rep = {"meshlane": version("meshlane"), "format": fmt,
       "nodes_in": len(src.points), "nodes_out": len(dst.points),
       "area_in": area(src), "area_out": area(dst),
       "groups_out": groups(dst)}
rep["nodes_ok"] = rep["nodes_in"] == rep["nodes_out"]
rep["area_ok"] = abs(rep["area_in"] - rep["area_out"]) <= 1e-9 * max(rep["area_in"], 1e-300)
rep["groups_missing"] = [g for g in need if not any(g in x for x in rep["groups_out"])]
json.dump(rep, open("mesh_check.json", "w"), indent=1)
print(json.dumps(rep, indent=1))
if not (rep["nodes_ok"] and rep["area_ok"]):
    sys.exit("mesh conversion changed the node count or the area: refusing to run the engine")
if rep["groups_missing"]:
    sys.exit("mesh conversion lost physical groups %s: the periodic constraints need them" % rep["groups_missing"])
"#;

