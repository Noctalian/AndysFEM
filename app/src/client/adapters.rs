//! One adapter per engine. Each turns the neutral job into that engine's native job files.
//! Geometry enters once (the Gmsh script, shared), mesh conversion goes through meshlane,
//! and each engine pairs its own periodic nodes and extracts the effective stress its own way.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, PartialOrd, Ord)]
pub enum Engine {
    /// the rebuilt (reverse-engineered) MAPDL-compatible solver of this program, run in-process
    Local,
    CodeAster,
    Fenicsx,
    Mapdl,
}

impl Engine {
    pub const ALL: [Engine; 4] = [Engine::Local, Engine::CodeAster, Engine::Fenicsx, Engine::Mapdl];
    pub fn key(self) -> &'static str {
        match self {
            Engine::Local => "rebuilt_local",
            Engine::CodeAster => "code_aster",
            Engine::Fenicsx => "fenicsx",
            Engine::Mapdl => "mapdl",
        }
    }
    pub fn label(self) -> &'static str {
        match self {
            Engine::Local => "Rebuilt MAPDL-compatible solver",
            Engine::CodeAster => "Code_Aster",
            Engine::Fenicsx => "FEniCSx (DOLFINx 0.11)",
            Engine::Mapdl => "Ansys MAPDL (reference)",
        }
    }
    pub fn role(self) -> &'static str {
        match self {
            Engine::Local => "reverse-engineered solver, runs in-process (no container, no licence)",
            Engine::CodeAster => "open-source engine A (planned)",
            Engine::Fenicsx => "open-source engine B (candidate, not yet decided)",
            Engine::Mapdl => "commercial reference on benchmark cells",
        }
    }
    pub fn mesh_format(self) -> &'static str {
        match self {
            Engine::Local => "msh (read directly)",
            Engine::CodeAster => "med",
            Engine::Fenicsx => "msh",
            Engine::Mapdl => "cdb",
        }
    }
    pub fn pairing(self) -> &'static str {
        match self {
            Engine::Local => "CE equations from node pairs, penalty coupling in the rebuilt solver",
            Engine::CodeAster => "LIAISON_GROUP with TRAN (Lagrange multipliers)",
            Engine::Fenicsx => "dolfinx_mpc slave elimination (geometrical periodic constraint)",
            Engine::Mapdl => "CE equations from node pairs found in the PyMAPDL script",
        }
    }
    pub fn stress_route(self) -> &'static str {
        match self {
            Engine::Local => "Hill's lemma over the constraint forces",
            Engine::CodeAster => "volume average of SIGM_ELGA (POST_ELEM INTEGRALE)",
            Engine::Fenicsx => "volume average of sigma(E + eps(v)) by assembled integral",
            Engine::Mapdl => "volume average from element tables (VOLU x S)",
        }
    }
}

